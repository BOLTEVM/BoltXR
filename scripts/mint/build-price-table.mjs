// Regenerates the mint price curve in both places it lives:
//   contracts/src/WatchPriceTable.sol  (what the contract charges)
//   lib/mint/priceTable.ts             (what the mint modal shows before the chain answers)
//
//   node scripts/mint/build-price-table.mjs
//
// Curve: mint #n of 150 costs 0.001 ETH × 1000^((n−1)/149) — #1 is 0.001 ETH, #150 is exactly
// 1 ETH, every mint lifts the next price by ~4.75 %. Prices are rounded to 4 significant figures
// and stored in microether (1e12 wei), so each fits in 3 bytes (450 bytes for the whole table).
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..', '..');

export const SUPPLY = 150;
export const FIRST_ETH = 0.001;
export const LAST_ETH = 1;
const MICRO_PER_ETH = 1_000_000;

/** Price of mint #n in microether. */
export function microPrice(n) {
    const eth = FIRST_ETH * Math.pow(LAST_ETH / FIRST_ETH, (n - 1) / (SUPPLY - 1));
    return Math.round(Number(eth.toPrecision(4)) * MICRO_PER_ETH);
}

export function buildTable() {
    const table = [];
    for (let n = 1; n <= SUPPLY; n++) table.push(microPrice(n));
    if (table[0] !== FIRST_ETH * MICRO_PER_ETH) throw new Error(`first price ${table[0]}`);
    if (table[SUPPLY - 1] !== LAST_ETH * MICRO_PER_ETH) throw new Error(`last price ${table[SUPPLY - 1]}`);
    for (let i = 1; i < SUPPLY; i++) if (!(table[i] > table[i - 1])) throw new Error(`price must rise at #${i + 1}`);
    if (table.some(v => v >= 1 << 24)) throw new Error('a price does not fit in 3 bytes');
    return table;
}

export function tableHex(table) {
    return table.map(v => v.toString(16).padStart(6, '0')).join('');
}

function main() {
    const table = buildTable();
    const hex = tableHex(table);
    const total = table.reduce((a, b) => a + b, 0);
    const fmt = v => (v / MICRO_PER_ETH).toString();

    const sol = `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

/**
 * @title WatchPriceTable
 * @notice The Iced-Out XR Watches mint curve: mint #n of ${SUPPLY} costs
 *         ${FIRST_ETH} ETH x 1000^((n-1)/${SUPPLY - 1}), rounded to 4 significant figures.
 *         #1 = ${fmt(table[0])} ETH, #75 = ${fmt(table[74])} ETH, #${SUPPLY} = ${fmt(table[SUPPLY - 1])} ETH;
 *         every mint lifts the next price (~4.75 %). Selling out raises ${fmt(total)} ETH.
 * @dev GENERATED by scripts/mint/build-price-table.mjs - do not edit by hand.
 *      Three big-endian bytes per mint, in microether (1e12 wei).
 */
library WatchPriceTable {
    uint256 internal constant COUNT = ${SUPPLY};
    uint256 internal constant UNIT = 1e12;

    bytes internal constant TABLE =
        hex"${hex}";

    error PriceIndexOutOfRange(uint256 n);

    /// @notice Price in wei of mint number \`n\` (1-based).
    function priceOf(uint256 n) internal pure returns (uint256) {
        if (n == 0 || n > COUNT) revert PriceIndexOutOfRange(n);
        bytes memory t = TABLE;
        return _read(t, n) * UNIT;
    }

    /// @notice Total in wei of the \`quantity\` mints starting at mint number \`first\`.
    function sum(uint256 first, uint256 quantity) internal pure returns (uint256 total) {
        if (quantity == 0) return 0;
        uint256 last = first + quantity - 1;
        if (first == 0 || last > COUNT) revert PriceIndexOutOfRange(first == 0 ? 0 : last);
        bytes memory t = TABLE;
        for (uint256 n = first; n <= last; ++n) total += _read(t, n);
        total *= UNIT;
    }

    function _read(bytes memory t, uint256 n) private pure returns (uint256) {
        uint256 i = (n - 1) * 3;
        return (uint256(uint8(t[i])) << 16) | (uint256(uint8(t[i + 1])) << 8) | uint256(uint8(t[i + 2]));
    }
}
`;

    const ts = `/**
 * lib/mint/priceTable.ts — the mint price curve, mirrored from the contract.
 *
 * GENERATED by scripts/mint/build-price-table.mjs — do not edit by hand. The contract's
 * contracts/src/WatchPriceTable.sol is generated from the same numbers; the modal uses this
 * copy to draw the curve and to quote before (or without) a chain connection, and always
 * prefers the contract's own \`quote()\` when it can reach it.
 */

export const SUPPLY = ${SUPPLY};

/** Wei per table unit (1 microether). */
const UNIT = 1_000_000_000_000n;

/** Price of mint #n (index n − 1) in microether. */
export const PRICE_MICRO: readonly number[] = [${table.join(', ')}];

/** Price in wei of mint number \`n\` (1-based). */
export function priceWei(n: number): bigint {
    const v = PRICE_MICRO[n - 1];
    if (v === undefined) throw new RangeError(\`No mint #\${n}\`);
    return BigInt(v) * UNIT;
}

/** Total in wei of \`quantity\` mints starting at mint number \`first\`. */
export function quoteWei(first: number, quantity: number): bigint {
    let total = 0n;
    for (let n = first; n < first + quantity; n++) total += priceWei(n);
    return total;
}

/** Price of mint #n in ETH, for display and charts. */
export function priceEth(n: number): number {
    return PRICE_MICRO[n - 1] / 1_000_000;
}

/** What selling out raises, in ETH. */
export const SELL_OUT_ETH = ${fmt(total)};
`;

    fs.writeFileSync(path.join(root, 'contracts', 'src', 'WatchPriceTable.sol'), sol);
    fs.mkdirSync(path.join(root, 'lib', 'mint'), { recursive: true });
    fs.writeFileSync(path.join(root, 'lib', 'mint', 'priceTable.ts'), ts);
    console.log(`price table: #1 ${fmt(table[0])} · #75 ${fmt(table[74])} · #150 ${fmt(table[149])} ETH · sell-out ${fmt(total)} ETH`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'))) main();
